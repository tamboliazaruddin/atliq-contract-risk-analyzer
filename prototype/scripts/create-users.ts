import "./env";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { DERIVED_DIR } from "../src/lib/config";
import { hashPassword } from "../src/lib/auth/users";

/**
 * Creates the demo accounts (AtliQ people from the dataset) with random passwords.
 *   npm run users                 → (re)generate all passwords
 *   npm run users -- jay          → reset one user's password
 * Only scrypt hashes go into data/derived/users.json (safe to commit). Plain passwords are written to
 * DEMO_ACCOUNTS.local.txt (git-ignored) for the demo — share them privately, never commit them.
 * Also adds a random AUTH_SECRET to .env.local if none is set.
 */
const PEOPLE = [
  { username: "karandeep", name: "Karandeep", title: "CEO · authorised signer", role: "signer" as const },
  { username: "bhavin", name: "Bhavin", title: "Founder", role: "stakeholder" as const },
  { username: "dhaval", name: "Dhaval", title: "Founder", role: "stakeholder" as const },
  { username: "jay", name: "Jay", title: "Sales executive", role: "stakeholder" as const },
  { username: "pranav", name: "Pranav", title: "CTO", role: "stakeholder" as const },
];

const only = process.argv.slice(2).filter((a) => !a.startsWith("-"));
const usersPath = path.join(DERIVED_DIR, "users.json");
const existing: Record<string, unknown>[] = fs.existsSync(usersPath) ? JSON.parse(fs.readFileSync(usersPath, "utf8")).users : [];
const plain: string[] = [];
const users = PEOPLE.map((p) => {
  const prev = existing.find((e) => e.username === p.username);
  if (prev && only.length && !only.includes(p.username)) return prev;
  const password = crypto.randomBytes(9).toString("base64url");
  plain.push(`${p.username.padEnd(10)} ${password}   (${p.title})`);
  return { ...p, ...hashPassword(password) };
});
fs.writeFileSync(usersPath, JSON.stringify({ _about: "Demo accounts. Passwords are scrypt-hashed; regenerate with `npm run users`.", users }, null, 2));

const out = "DEMO_ACCOUNTS.local.txt";
const header = `AtliQ Contract Risk Analyzer — demo accounts (generated ${new Date().toISOString()})\nKeep private. Do not commit. Regenerate with: npm run users\n\n`;
const prevLines = fs.existsSync(out) ? fs.readFileSync(out, "utf8").split("\n").filter((l) => /^\w+\s{2,}/.test(l) && !plain.some((p) => p.startsWith(l.split(" ")[0] + " "))) : [];
fs.writeFileSync(out, header + [...prevLines, ...plain].join("\n") + "\n");

if (!process.env.AUTH_SECRET) {
  const secret = crypto.randomBytes(32).toString("base64url");
  fs.appendFileSync(".env.local", `\n# Session signing secret (generated by npm run users)\nAUTH_SECRET=${secret}\n`);
  console.log("Added AUTH_SECRET to .env.local");
}
console.log(`Updated ${plain.length} account(s) in ${usersPath}. Passwords written to ${out} (git-ignored).`);
